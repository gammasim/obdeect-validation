"""Closed loss accounting of ``obdeect propagation run`` (case propagation.loss-accounting).

Every photon of the input has exactly one fate, and the run summary must show it. Input streams are
written with the stream Writer (sky frame, explicit directions); the runs use the Python API, the same
C++ core as the command line, whose summary has ``dropped_by_reason``. The command line summary line
(photons in, out, dropped) is checked against the API for the counts.

Populations (N photons per category, one telescope, observation level 2000 m a.s.l.):

- plane population, telescope plane 500 m above the level, no profile (no refraction, no turnover):
  reach_down (z 800, downward) and reach_up (z 100, upward) reach the plane; moving_away_down (z 300,
  downward) and moving_away_up (z 700, upward) are moving_away; horizontal (cz = 0); below_ground_down and
  below_ground_up (z -10). The expected reason of each category is written here, not taken from the code.
- sphere population, telescope centre C at 5 m (sphere R = 12 m, so the sphere reaches below the level)
  and at 500 m (control): hit_down (z 1000, aimed at C) reaches the sphere; side_down (z 1000, 300 m off
  axis, vertical) misses it; below_ground_down (z -10) is below_ground.
- scattering populations (plane 500 m, sphere 5 m and 500 m): primaries at zenith 30 deg (no horizontal
  primaries, so the plane and sphere kernels emit the same rows) from z 1000 (down), z 100 (up) and
  z 3000 (down), plus hit_down for the sphere telescopes.

Checks and the gate of each metric:

- Counts (balance, dropped sum, reason counts, reaching counts): exact integers, atol 0. Each photon has one
  fate, so the difference is an integer that must be zero; no tolerance can be justified for a count.
- Triggered reasons: every reason that the input was built to trigger is > 0 (count of missing ones, atol 0).
- Weights (summary weight_out against the sum of w in the output stream, and against the expected weight of
  the reaching photons, which have w = 1): relative error, atol 1e-9. The summary sums float32 weights in
  double precision and the reader returns the same float32 values, so the only difference is the order of
  summation (about 1e-15 relative for these sizes). 1e-9 leaves a factor 1e6 margin and is far below the
  float32 resolution (6e-8), so a real loss of weight would be seen.
- Thinning (real atmosphere table, thinned mode): the photons removed by the acceptance draw are reported as
  ``thinned_out``; the balance subtracts round(thinned_out) and must be 0 (it is not weakened).
- Scattering: the scattered photons generated by the single-scattering kernel are the rows that
  ``obdeect.propagation.scatter`` returns (same seed, event and first index as the run; a scattering point
  inside the sphere gives no row, by design). They must equal the scattered photons written plus the
  scattered photons dropped that the summary reports (``scattered_dropped``), plus zero-weight rows (which
  carry no weight). The written scattered photons are the output rows minus the rows of the same run without
  scattering (primaries come first in the block; the check confirms they are identical row by row). The
  control (telescope at 500 m, sphere) and the plane and low-sphere runs all have the same gate, 0. A nonzero
  value is the unaccounted loss: scattered photons that the stage generates but neither writes, reports as
  dropped, nor finds to have zero weight. The summary keys are read with a clear failure when missing, so an
  obdeect without the accounting keys fails rather than passing.
"""

from __future__ import annotations

import math
import re
from pathlib import Path

import numpy as np

from obdeect_validation.adapters import common
from obdeect_validation.adapters import endtoend_common as e2e

SEED = 20261123
SITE_M = 2000.0
TELESCOPE_R_M = 12.0
PLANE_TELESCOPE_Z_M = 500.0
LOW_TELESCOPE_Z_M = 5.0
N = 25  # photons per category, population runs
N_SCATTER = 40  # photons per category, scattering runs
SCATTERING_POINTS = 8
ZENITH_DEG = 30.0
WAVELENGTH_NM = 355.0  # inside the scattering table (340 to 400 nm)
REASONS = (
    "moving_away",
    "horizontal",
    "below_ground",
    "turns_over",
    "not_bendable",
    "misses_level",
    "misses_sphere",
)
PLANE_EXPECTED = ("moving_away", "horizontal", "below_ground")
SPHERE_EXPECTED = ("misses_sphere", "below_ground")
COLUMNS = ("x", "y", "z", "cx", "cy", "cz", "t", "w", "wavelength")
ROOT = Path(__file__).resolve().parents[3]  # obdeect-validation
FIXTURES = ROOT / "fixtures"
UNIT_TABLE = FIXTURES / "unit-transmission.dat"
ATMOSPHERE_TABLE = FIXTURES / "atm_trans_2000_1_10_0_0_2000.dat"
SCATTERING_TABLE = FIXTURES / "scattering_exponential.dat"

SUMMARY_LINE = re.compile(
    r"photons in (\d+), out (\d+) \(weight [^)]*\), dropped (\d+)"
)


def version() -> str:
    return common.package_version("obdeect-propagation")


# ------------------------------------------------------------------ tables


def zero_table(path: Path) -> Path:
    """Unit-transmission table (zero optical depth), bottom at the observation level, rows < 1000 nm."""
    kept = []
    for line in UNIT_TABLE.read_text(encoding="utf-8").splitlines():
        fields = line.split()
        if line.startswith("#") or (fields and int(fields[0]) < 1000):
            kept.append(line)
    text = common.zero_depth_table("\n".join(kept) + "\n", SITE_M)
    path.write_text(text, encoding="utf-8")
    return path


# ------------------------------------------------------------------ populations


def _direction(zenith_deg, azimuth_deg):
    th, az = math.radians(zenith_deg), math.radians(azimuth_deg)
    return (
        math.sin(th) * math.cos(az),
        math.sin(th) * math.sin(az),
        math.cos(th),
    )


def _columns(rows):
    cols = {k: np.asarray([r[k] for r in rows], dtype=np.float32) for k in COLUMNS}
    return cols


def _row(rng, x, y, z, cx, cy, cz):
    return {
        "x": x,
        "y": y,
        "z": z,
        "cx": cx,
        "cy": cy,
        "cz": cz,
        "t": 0.0,
        "w": 1.0,
        "wavelength": WAVELENGTH_NM,
    }


def plane_population(rng):
    """Categories of the plane population: (name, rows, expected reason or None for reaching)."""
    categories = []

    def group(name, z, sign, reason, horizontal=False):
        rows = []
        for _ in range(N):
            x, y = rng.uniform(-50, 50), rng.uniform(-50, 50)
            if horizontal:
                rows.append(_row(rng, x, y, z, 1.0, 0.0, 0.0))
                continue
            cx, cy, cz = _direction(ZENITH_DEG, rng.uniform(0, 360))
            rows.append(_row(rng, x, y, z, cx, cy, sign * cz))
        categories.append((name, rows, reason))

    group("reach_down", 800.0, -1, None)
    group("moving_away_down", 300.0, -1, "moving_away")
    group("reach_up", 100.0, +1, None)
    group("moving_away_up", 700.0, +1, "moving_away")
    group("horizontal", 200.0, 0, "horizontal", horizontal=True)
    group("below_ground_down", -10.0, -1, "below_ground")
    group("below_ground_up", -10.0, +1, "below_ground")
    return categories


def sphere_population(rng, centre):
    """Categories of the sphere population for a telescope centre (x, y, z) above the level."""
    cx_t, cy_t, cz_t = centre
    categories = []
    rows = []
    for _ in range(N):
        azimuth = rng.uniform(0, 360)
        ux, uy, uz = _direction(ZENITH_DEG, azimuth)
        uz = -uz  # downward
        # Aim at a point Q within 2 m of C, starting at z = 1000 m
        qx = cx_t + rng.uniform(-2, 2)
        qy = cy_t + rng.uniform(-2, 2)
        s = (1000.0 - cz_t) / math.cos(math.radians(ZENITH_DEG))
        rows.append(_row(rng, qx - s * ux, qy - s * uy, 1000.0, ux, uy, uz))
    categories.append(("hit_down", rows, None))
    rows = []
    for _ in range(N):
        x = cx_t + rng.choice([-1.0, 1.0]) * rng.uniform(280, 320)
        rows.append(_row(rng, x, cy_t, 1000.0, 0.0, 0.0, -1.0))
    categories.append(("side_down", rows, "misses_sphere"))
    rows = []
    for _ in range(N):
        ux, uy, uz = _direction(ZENITH_DEG, rng.uniform(0, 360))
        rows.append(
            _row(rng, rng.uniform(-50, 50), rng.uniform(-50, 50), -10.0, ux, uy, -uz)
        )
    categories.append(("below_ground_down", rows, "below_ground"))
    return categories


def scatter_primaries(rng, sphere_centre=None):
    """Primaries for the scattering runs (no horizontal photons): down from 1000 m, up from 100 m,
    down from 3000 m; with sphere_centre, also hit_down aimed at the telescope centre."""
    rows = []
    for z, sign in ((1000.0, -1), (100.0, +1), (3000.0, -1)):
        for _ in range(N_SCATTER):
            ux, uy, uz = _direction(ZENITH_DEG, rng.uniform(0, 360))
            rows.append(
                _row(
                    rng,
                    rng.uniform(-50, 50),
                    rng.uniform(-50, 50),
                    z,
                    ux,
                    uy,
                    sign * uz,
                )
            )
    if sphere_centre is not None:
        cx_t, cy_t, cz_t = sphere_centre
        for _ in range(N_SCATTER):
            ux, uy, uz = _direction(ZENITH_DEG, rng.uniform(0, 360))
            uz = -uz
            qx = cx_t + rng.uniform(-2, 2)
            qy = cy_t + rng.uniform(-2, 2)
            s = (1000.0 - cz_t) / math.cos(math.radians(ZENITH_DEG))
            rows.append(_row(rng, qx - s * ux, qy - s * uy, 1000.0, ux, uy, uz))
    return rows


def write_input(path: Path, telescope, rows):
    from obdeect_validation.adapters import upward_common as uc

    return uc.write_stream(
        path,
        [telescope],
        [(1, _columns(rows))],
        refraction_applied=0,
        chunk_rows=64,
        run_extra={"telescope_r_m": [TELESCOPE_R_M]},
    )


# ------------------------------------------------------------------ runs


def run_api(stream, output, **options):
    from obdeect.propagation import propagate

    # No in-telescope path in the loss accounting. pathlen_m is required with extinction (and
    # rejected with extinction=False).
    if options.get("extinction", True) is not False:
        options.setdefault("pathlen_m", 0.0)
    return propagate(stream, output, site_altitude_m=SITE_M, seed=1, **options)


def run_cli(stream, output, transmission, log, **flags):
    """obdeect propagation run; its summary line (counts) parsed from stderr."""
    argv = [
        common.tool("obdeect"),
        "propagation",
        "run",
        "--transmission",
        str(transmission),
        "--pathlen",
        "0",
        "--site-altitude",
        str(SITE_M),
        "--seed",
        "1",
        "-i",
        str(stream),
        "-o",
        str(output),
    ]
    if flags.get("mode"):
        argv += ["--mode", flags["mode"]]
    if flags.get("sphere"):
        argv += ["--ground-representation", "sphere"]
    if flags.get("scattering"):
        argv += ["--scattering", str(flags["scattering"])]
    text = common.run_tool(argv, log)
    match = SUMMARY_LINE.search(text)
    if match is None:
        raise RuntimeError(f"no summary line in {log}")
    photons_in, photons_out, dropped = (int(v) for v in match.groups())
    return {"photons_in": photons_in, "photons_out": photons_out, "dropped": dropped}


def stream_weight(path) -> tuple[float, int]:
    rows = e2e.photon_rows(path)
    if "w" not in rows:
        return 0.0, 0
    return float(np.sum(rows["w"].astype(np.float64))), len(rows["w"])


def expected_reasons(categories):
    counts = {r: 0 for r in REASONS}
    reaching = 0
    total = 0
    for _name, rows, reason in categories:
        total += len(rows)
        if reason is None:
            reaching += len(rows)
        else:
            counts[reason] += len(rows)
    return counts, reaching, total


def population_metrics(prefix, summary, categories, reasons, cli=None, stream_out=None):
    """Balance, reason and reaching counts of one population run (integers) and the weight checks."""
    expected, reaching, total = expected_reasons(categories)
    by_reason = {r: int(summary["dropped_by_reason"][r]) for r in REASONS}
    out = {
        f"{prefix}_balance_error": balance_error(summary),
        f"{prefix}_dropped_sum_error": int(
            summary["dropped"] - sum(by_reason.values())
        ),
        f"{prefix}_reason_error": int(
            sum(abs(by_reason[r] - expected[r]) for r in REASONS)
        ),
        f"{prefix}_reaching_error": int(summary["photons_out"] - reaching),
        f"{prefix}_input_count_error": int(summary["photons_in"] - total),
        f"{prefix}_triggered_missing": int(
            sum(1 for r in reasons if by_reason[r] == 0)
        ),
    }
    if cli is not None:
        out[f"{prefix}_cli_mismatch"] = int(
            sum(
                abs(cli[k] - summary[k])
                for k in ("photons_in", "photons_out", "dropped")
            )
        )
    if stream_out is not None:
        weight, _rows = stream_weight(stream_out)
        out[f"{prefix}_weight_vs_stream_rel"] = abs(
            summary["weight_out"] - weight
        ) / max(weight, 1e-300)
        out[f"{prefix}_weight_vs_expected_rel"] = abs(
            summary["weight_out"] - reaching
        ) / max(reaching, 1e-300)
    details = {
        "summary": summary,
        "expected_reason": expected,
        "expected_reaching": reaching,
        "expected_total": total,
        "cli": cli,
    }
    return out, details


def scatter_metrics(
    prefix, base_summary, scatter_summary, generated, base_out, scatter_out, zero_rows
):
    """Unaccounted scattered photons of one scattering run (see the module docstring)."""
    base_rows = e2e.photon_rows(base_out)
    scat_rows = e2e.photon_rows(scatter_out)
    n_base = len(base_rows["x"]) if "x" in base_rows else 0
    names = sorted(k for k in base_rows if not k.startswith("_"))
    changed = 0
    if sorted(k for k in scat_rows if not k.startswith("_")) != names:
        changed += 1  # the columns of the two outputs differ
    for name in names:
        if name not in scat_rows or len(scat_rows[name]) < n_base:
            changed += n_base
            continue
        changed += int(np.count_nonzero(base_rows[name] != scat_rows[name][:n_base]))
    written_scattered = int(
        scatter_summary["photons_out"] - base_summary["photons_out"]
    )
    reported_scattered_dropped = int(
        _summary_value(scatter_summary, "scattered_dropped", "scatter run")
    )
    unaccounted = scattered_unaccounted(
        generated, zero_rows, written_scattered, reported_scattered_dropped
    )
    weight, _ = stream_weight(scatter_out)
    metrics = {
        f"{prefix}_setup_error": int(generated == 0),
        f"{prefix}_primary_rows_changed": int(changed),
        f"{prefix}_primary_drops_changed": int(
            sum(
                abs(
                    int(scatter_summary["dropped_by_reason"][r])
                    - int(base_summary["dropped_by_reason"][r])
                )
                for r in REASONS
            )
            + abs(int(scatter_summary["photons_in"]) - int(base_summary["photons_in"]))
        ),
        f"{prefix}_unaccounted": unaccounted,
        f"{prefix}_weight_vs_stream_rel": abs(scatter_summary["weight_out"] - weight)
        / max(weight, 1e-300),
    }
    details = {
        "generated": int(generated),
        "zero_weight_rows": int(zero_rows),
        "written_scattered": written_scattered,
        "reported_scattered_dropped": reported_scattered_dropped,
        "base_photons_out": int(base_summary["photons_out"]),
        "scatter_summary": scatter_summary,
        "base_summary": base_summary,
        "primary_rows_compared": n_base,
    }
    return metrics, details


def scattered_unaccounted(generated, zero_rows, written, reported_dropped) -> int:
    """Generated scattered rows not written, not reported as dropped and not zero weight (exact integer)."""
    return int(generated) - int(zero_rows) - int(written) - int(reported_dropped)


def _summary_value(summary, key, label):
    """A key of the propagation summary; a clear failure when the obdeect version lacks it."""
    if key not in summary:
        raise RuntimeError(
            f"propagation summary of the {label} lacks '{key}': the obdeect version is too old for the "
            "accounting keys of docs/propagation/propagation.md"
        )
    return summary[key]


def balance_error(summary) -> int:
    """photons in - photons out - dropped - thinned_out (exact integer, 0 when every photon is accounted for)."""
    return (
        int(summary["photons_in"])
        - int(summary["photons_out"])
        - int(summary["dropped"])
        - round(_summary_value(summary, "thinned_out", "run"))
    )


def generated_scattered(columns_rows, telescope, centre_r, transmission):
    """Scattered rows of the single-scattering kernel for these primaries (one row per point and telescope)."""
    from obdeect.propagation import TransmissionTable, scatter
    from obdeect.propagation.scattering import ScatteringTable

    cols = _columns(columns_rows)
    table = ScatteringTable(str(SCATTERING_TABLE))
    table_transmission = TransmissionTable(str(transmission), site_altitude_m=SITE_M)
    result = scatter(
        cols,
        table,
        table_transmission,
        [(1, telescope[0], telescope[1], telescope[2], centre_r)],
        1,  # the seed of the propagation runs (run_api)
        1,
        0,
        SCATTERING_POINTS,
    )
    generated = sum(len(v["x"]) for v in result.values())
    zero = sum(int(np.count_nonzero(v["w"] == 0)) for v in result.values())
    return int(generated), int(zero)


# ------------------------------------------------------------------ analysis


def analyse(root: Path) -> tuple[dict, dict]:
    rng = np.random.default_rng(SEED)
    zero = zero_table(root / "zero-transmission.dat")
    metrics: dict = {}
    details: dict = {"seed": SEED, "obdeect_propagation_version": version()}
    plane_telescope = (0.0, 0.0, PLANE_TELESCOPE_Z_M)
    low_telescope = (0.0, 0.0, LOW_TELESCOPE_Z_M)
    control_telescope = (0.0, 0.0, PLANE_TELESCOPE_Z_M)

    # Population, plane representation: thinned (unit transmission), weighted, geometry only.
    plane = plane_population(rng)
    rows = [r for _n, rs, _e in plane for r in rs]
    stream = write_input(root / "plane-in.pst", plane_telescope, rows)
    for label, options in {
        "plane_thinned": {"transmission": str(zero)},
        "plane_weighted": {"transmission": str(zero), "mode": "weighted"},
        "plane_geometry": {"extinction": False},
    }.items():
        out_file = root / f"{label}.pst"
        summary = run_api(stream, out_file, **options)
        cli = None
        if label == "plane_weighted":
            cli = run_cli(
                stream,
                root / "plane_weighted-cli.pst",
                zero,
                root / "plane_weighted-cli.log",
                mode="weighted",
            )
        m, d = population_metrics(
            label, summary, plane, PLANE_EXPECTED, cli=cli, stream_out=out_file
        )
        metrics.update(m)
        details[label] = d

    # Thinned with the real atmosphere table: the acceptance draw removes photons; the summary
    # has no count for them (balance expected 0).
    out_file = root / "plane_thinned_atmosphere.pst"
    summary = run_api(stream, out_file, transmission=str(ATMOSPHERE_TABLE))
    metrics["plane_thinned_atmosphere_balance_error"] = balance_error(summary)
    details["plane_thinned_atmosphere"] = {"summary": summary}

    # Sphere representation: telescope centre at 5 m (sphere below the level), and 500 m (sphere).
    for label, centre in (("sphere_low", low_telescope),):
        sphere = sphere_population(rng, centre)
        rows = [r for _n, rs, _e in sphere for r in rs]
        stream = write_input(root / f"{label}-in.pst", centre, rows)
        out_file = root / f"{label}.pst"
        summary = run_api(
            stream,
            out_file,
            transmission=str(zero),
            mode="weighted",
            ground_representation="sphere",
        )
        m, d = population_metrics(
            f"{label}_weighted", summary, sphere, SPHERE_EXPECTED, stream_out=out_file
        )
        metrics.update(m)
        details[f"{label}_weighted"] = d
        out_file = root / f"{label}_thinned.pst"
        summary = run_api(
            stream, out_file, transmission=str(zero), ground_representation="sphere"
        )
        m, d = population_metrics(f"{label}_thinned", summary, sphere, SPHERE_EXPECTED)
        metrics.update(m)
        details[f"{label}_thinned"] = d

    # Scattering, plane representation.
    prim = scatter_primaries(rng)
    stream = write_input(root / "scatter-plane-in.pst", plane_telescope, prim)
    base_out = root / "scatter-plane-base.pst"
    scat_out = root / "scatter-plane.pst"
    base = run_api(stream, base_out, transmission=str(zero), mode="weighted")
    scat = run_api(
        stream,
        scat_out,
        transmission=str(zero),
        mode="weighted",
        scattering=str(SCATTERING_TABLE),
        scattering_points=SCATTERING_POINTS,
    )
    generated, zero_rows = generated_scattered(
        prim, plane_telescope, TELESCOPE_R_M, zero
    )
    m, d = scatter_metrics(
        "scatter_plane", base, scat, generated, base_out, scat_out, zero_rows
    )
    metrics.update(m)
    details["scatter_plane"] = d

    # Scattering, sphere representation: low telescope (drops below ground) and control at 500 m.
    for label, centre in (
        ("scatter_sphere_low", low_telescope),
        ("scatter_sphere_control", control_telescope),
    ):
        prim = scatter_primaries(rng, sphere_centre=centre)
        stream = write_input(root / f"{label}-in.pst", centre, prim)
        base_out = root / f"{label}-base.pst"
        scat_out = root / f"{label}.pst"
        base = run_api(
            stream,
            base_out,
            transmission=str(zero),
            mode="weighted",
            ground_representation="sphere",
        )
        scat = run_api(
            stream,
            scat_out,
            transmission=str(zero),
            mode="weighted",
            ground_representation="sphere",
            scattering=str(SCATTERING_TABLE),
            scattering_points=SCATTERING_POINTS,
        )
        generated, zero_rows = generated_scattered(prim, centre, TELESCOPE_R_M, zero)
        m, d = scatter_metrics(
            label, base, scat, generated, base_out, scat_out, zero_rows
        )
        metrics.update(m)
        details[label] = d

    return metrics, details


def main() -> None:
    common.results_main(analyse, __doc__.splitlines()[0])


if __name__ == "__main__":
    main()
