"""Optics isolation: CORSIKA -> obdeect trace-stream -> sim_telarray camera (Bypass_Optics), against direct sim_telarray.

Both sides use the same model: the sim_telarray configuration generated by simtools for one array
element of a production version (--config; CTAO.cfg is the array header, CTAO-<element>.cfg the
telescope). One telescope (sim_telarray index 1, at the array origin). Both runs use a unit
atmosphere (optical depth 0). Factors and where they are applied are recorded in details.json.

Parameters (defaults are the LSTN-01 7.0.0 North chain, zenith 20 deg, azimuth 180 deg):
  --telescope      array element (LSTN-01, MSTN-01, SSTS-01, MSTS-01, LSTS-01, ...)
  --site           observatory of the configuration (checked against the configuration)
  --model-version  production version used for the obdeect model compile
  --input          CORSIKA IACT input (shower file)
  --zenith         telescope zenith [deg]; default: the zenith of the shower run header
  --azimuth        telescope azimuth [deg] in the array frame (simtools telescope phi); default 180.
                   Not read from the header: EventIO's shower azimuth is in the CORSIKA frame and
                   is not the telescope azimuth. Cases set it explicitly.

The camera-frame stream carries the mirror class of the telescope: sim_telarray mirror_class 2 (dual
mirror) gives camera map class 2 and Bypass_Optics=2 (both mirrors bypassed). obdeect prints the
Bypass_Optics value of each converted telescope; the candidate run uses that printed value.

Physics limits: photo-electron relative bias max(1 %, 5 standard errors); image reduced chi2 mean at
most 2; arrival-time mean bias max(0.05 ns, 5 standard errors).

Trigger: each shower reaches both chains as one camera event (sim_telarray id 100 * shower + reuse).
The two chains draw independent random sequences (the candidate photons are re-generated by obdeect),
so whether an image passes the local trigger is a random outcome, and a single shower can trigger in
one chain only. Equal event sets are therefore not a deterministic expectation and camera_event_id_delta
is reported, not gated. The gate is a paired test of the trigger probability per telescope: exact
two-sided McNemar on the discordant showers, p > 0.01 (plan.md). It is not a 0-mismatch count.
"""

import math
import re
from pathlib import Path

import numpy as np
from eventio.iact import IACTFile

from obdeect_validation.adapters import chain_showers as cs
from obdeect_validation.adapters import common
from obdeect_validation.adapters import obdeect_cli as cli

UNIT_ATMOSPHERE = common.VALIDATION / "fixtures/unit-transmission.dat"
MODEL, VERSION = "LSTN-01", "7.0.0"  # defaults: array element and production version
SITE = "North"
SEED = common.SIMTEL_SEED
TELESCOPES = (1,)
#: Legend label of the one telescope of the run, keyed by the 0-based photoelectron index (sim_telarray).
CAMERA_NAMES = {0: f"{MODEL} (model {VERSION})"}
ZENITH_DEG, AZIMUTH_DEG = 20, 180  # defaults
#: Header zenith and explicit zenith must agree within this tolerance [deg].
ZENITH_TOLERANCE_DEG = 1e-3
#: Trigger test: exact McNemar p-value on the discordant events per telescope (plan.md, p > 0.01).
TRIGGER_P_LIMIT = 0.01


def cfg_value(text, key, default=None):
    match = re.search(rf"^\s*{key}\s*=\s*([^%\n]+)", text, re.MULTILINE)
    return match.group(1).strip() if match else default


def deg_text(value):
    """Degrees as written to the command lines: 20.0 -> "20", 22.5 -> "22.5"."""
    return f"{round(float(value), 6):g}"


def camera_label(telescope, model_version):
    return f"{telescope} (model {model_version})"


def camera_rotation_deg(config_dir, cfg_text):
    camera = cfg_value(cfg_text, "camera_config_file")
    rotate = re.search(
        r"^\s*Rotate\s+([-\d.eE+]+)", (config_dir / camera).read_text(), re.MULTILINE
    )
    if rotate is None:
        raise ValueError(f"camera file {camera} has no Rotate line")
    return float(rotate.group(1))


def camera_class(cfg_text):
    """obdeect camera-map mirror class of a telescope: 2 for dual mirrors (sim_telarray mirror_class 2), else 1."""
    return 2 if int(cfg_value(cfg_text, "mirror_class", "0")) == 2 else 1


def header_pointing(source):
    """Shower geometry of the EventIO run, all showers: zenith range and mean [deg], and the
    N->E telescope azimuth [deg].

    The shower azimuth in the event header equals the CORSIKA PHIP. Telescope (N->E) azimuth =
    PHIP + 180 (PHIP 0 is N->E 180, as the default chain). All showers must share the azimuth.
    """
    zeniths, azimuths = [], []
    with IACTFile(source) as stream:
        for event in stream:
            zeniths.append(float(np.degrees(event.header["zenith"])))
            azimuths.append(float(np.degrees(event.header["azimuth"])))
    if not zeniths:
        raise ValueError(f"no showers in {source}")
    azimuths = np.asarray(azimuths)
    if np.ptp(azimuths) > ZENITH_TOLERANCE_DEG:
        raise ValueError(f"showers of {source} have different azimuths")
    return {
        "zenith_min_deg": min(zeniths),
        "zenith_max_deg": max(zeniths),
        "zenith_mean_deg": float(np.mean(zeniths)),
        "n_showers": len(zeniths),
        "telescope_azimuth_deg": float((azimuths[0] + 180.0) % 360.0),
        "header_azimuth_deg": float(azimuths[0]),
    }


def pointing(source, zenith=None, azimuth=None):
    """Telescope pointing [deg] as command-line text, and the header summary.

    zenith None: the mean shower zenith of the run (CORSIKA THETAP range). An explicit zenith must
    lie within the shower zenith range. azimuth None: the N->E azimuth from the header; an explicit
    azimuth must equal it.
    """
    header = header_pointing(source)
    tol = ZENITH_TOLERANCE_DEG
    if zenith is None:
        zenith = header["zenith_mean_deg"]
    elif not (
        header["zenith_min_deg"] - tol
        <= float(zenith)
        <= header["zenith_max_deg"] + tol
    ):
        raise ValueError(
            f"pointing zenith {zenith} deg outside the shower zenith range "
            f"{header['zenith_min_deg']:.6f}..{header['zenith_max_deg']:.6f} deg of {source}"
        )
    if azimuth is None:
        azimuth = header["telescope_azimuth_deg"]
    elif (
        abs((float(azimuth) - header["telescope_azimuth_deg"] + 180.0) % 360.0 - 180.0)
        > tol
    ):
        raise ValueError(
            f"pointing azimuth {azimuth} deg (N->E) differs from {header['telescope_azimuth_deg']} deg "
            f"derived from the shower header of {source}"
        )
    return deg_text(zenith), deg_text(azimuth), header


def factor_record(cfg_text, config_dir, bypass=1):
    """Factors of the matched model and where each is applied (sim_telarray reference vs candidate)."""
    return {
        "mirror_reflectivity": {
            "file": cfg_value(cfg_text, "mirror_reflectivity"),
            "reference": "sim_telarray ray tracing (Bypass_Optics=0)",
            "candidate": "obdeect compiled mirror response (trace-stream); sim_telarray not applied",
        },
        "mirror_degraded_reflection": {
            "value": cfg_value(cfg_text, "mirror_degraded_reflection"),
            "reference": "sim_telarray ray tracing (sim_absorb mirror_degraded)",
            "candidate": "obdeect compiled mirror response (compiler.py); sim_telarray "
            f"Bypass_Optics={bypass} only warns",
        },
        "telescope_transmission": {
            "value": cfg_value(cfg_text, "telescope_transmission"),
            "reference": "sim_telarray ray tracing (t0 kept)",
            "candidate": "obdeect trace-stream --telescope-transmission full (t0 and t(theta)); sim_telarray forces t0=1 under bypass",
        },
        "camera_transmission": {
            "value": cfg_value(cfg_text, "camera_transmission"),
            "reference": "sim_telarray",
            "candidate": "sim_telarray (Bypass_Optics=1, same value)",
        },
        "camera_degraded_efficiency": {
            "value": cfg_value(cfg_text, "camera_degraded_efficiency"),
            "reference": "sim_telarray",
            "candidate": "sim_telarray (same value)",
        },
        "quantum_efficiency": {
            "file": cfg_value(cfg_text, "quantum_efficiency"),
            "reference": "sim_telarray",
            "candidate": "sim_telarray (Bypass_Optics=1 first cut and second cut)",
        },
        "atmosphere": {
            "reference": "unit table (optical depth 0)",
            "candidate": "unit table (optical depth 0), no obdeect atmosphere stage",
        },
        "camera_rotation_deg": camera_rotation_deg(config_dir, cfg_text),
        "mirror_class": cfg_value(cfg_text, "mirror_class"),
    }


def triggered(events, key, tel):
    """True when telescope tel (1-based, as sim_telarray writes telescope_events) has an event."""
    if key not in events:
        return False
    fired = events[key].get("telescope_events", {})
    return tel in fired or str(tel) in fired


def camera_keys(source):
    """sim_telarray camera event id of each input shower, in file order.

    The id is 100 * shower number + reuse index, the reuse index counting the consecutive
    CORSIKA reuses of one shower from 0 (five per shower in these inputs; verified on the
    direct and candidate outputs, see camera_event_ids_of_reference check in main).
    """
    keys, reuse = [], {}
    with IACTFile(source) as stream:
        for event in stream:
            shower = int(event.event_number)
            index = reuse.get(shower, 0)
            reuse[shower] = index + 1
            keys.append(str(100 * shower + index))
    return keys


def mcnemar_exact_p(candidate_only, reference_only):
    """Two-sided exact McNemar (binomial) p-value on the discordant events."""
    n = candidate_only + reference_only
    if n == 0:
        return 1.0
    k = min(candidate_only, reference_only)
    tail = sum(math.comb(n, i) for i in range(k + 1)) / 2.0**n
    return min(1.0, 2.0 * tail)


def trigger_difference(reference, candidate, keys):
    """Paired trigger-probability comparison per telescope over the camera events of keys.

    difference: candidate minus reference trigger fraction; se: paired standard error of that
    difference (discordant pairs); mcnemar_p: exact two-sided McNemar p on the discordant events;
    flag: 1 when mcnemar_p is below TRIGGER_P_LIMIT. Counts: both, reference_only, candidate_only.
    """
    rows = {}
    for tel in TELESCOPES:
        both = reference_only = candidate_only = 0
        for key in keys:
            ref = triggered(reference, key, tel)
            cand = triggered(candidate, key, tel)
            both += ref and cand
            reference_only += ref and not cand
            candidate_only += cand and not ref
        n = len(keys)
        difference = (candidate_only - reference_only) / n if n else 0.0
        discordant = candidate_only + reference_only
        variance = (
            max(discordant - (candidate_only - reference_only) ** 2 / n, 0.0)
            if n
            else 0.0
        )
        se = float(np.sqrt(variance) / n) if n else 0.0
        p_value = mcnemar_exact_p(candidate_only, reference_only)
        rows[tel] = {
            "difference": float(difference),
            "se": se,
            "mcnemar_p": float(p_value),
            "flag": int(p_value < TRIGGER_P_LIMIT),
            "both": both,
            "reference_only": reference_only,
            "candidate_only": candidate_only,
        }
    return rows


def centroids(events):
    """Photo-electron-weighted centroid in pixel-index space per (event, telescope); not geometric."""
    result = {}
    for key, event in events.items():
        for tel, data in event.get("photoelectrons", {}).items():
            pe = np.asarray(data["photoelectrons"], dtype=float)
            if pe.sum() > 0:
                index = np.arange(len(pe))
                result[key, tel] = (
                    float((pe * index).sum() / pe.sum()),
                    float(pe.sum()),
                )
    return result


def centroid_offsets(reference, candidate):
    """Mean and max |centroid difference| in pixel-index units over matched (event, telescope) pairs."""
    left, right = centroids(reference), centroids(candidate)
    keys = sorted(set(left) & set(right))
    offsets = [right[k][0] - left[k][0] for k in keys]
    return {
        "centroid_matched_samples": len(offsets),
        "centroid_mean_index_offset": float(np.mean(offsets)) if offsets else 0.0,
        "centroid_max_abs_index_offset": float(np.max(np.abs(offsets)))
        if offsets
        else 0.0,
    }


def camera_map(root, rotation, mirror_class=1):
    camera = root / "camera-map.txt"
    camera.write_text(
        "# telescope_id mirror_class camera_rotation_deg\n"
        + "".join(f"{tel} {mirror_class} {rotation}\n" for tel in TELESCOPES)
    )
    return camera


def bypass_from_log(log):
    """Bypass_Optics value that obdeect stream to-simtel printed for the (single) telescope."""
    values = set(re.findall(r"Bypass_Optics=(\d)", Path(log).read_text()))
    if len(values) != 1:
        raise RuntimeError(
            f"expected one Bypass_Optics value in {log}, found {sorted(values)}"
        )
    return int(values.pop())


def propagation_table(root):
    """Zero-depth table for obdeect propagation: its rows must be below 1000 nm.

    The fixture's last row (1000 nm) is dropped; the table is zero everywhere. sim_telarray keeps
    the full table (common.write_zero_depth_table).
    """
    path = common.write_zero_depth_table(
        root, UNIT_ATMOSPHERE, name="unit-propagation.dat"
    )
    kept = []
    for line in path.read_text(encoding="utf-8").splitlines():
        fields = line.split()
        if fields and fields[0].isdigit() and int(fields[0]) >= 1000:
            continue
        kept.append(line)
    path.write_text("\n".join(kept) + "\n", encoding="utf-8")
    return path


def candidate_stream(
    root,
    source,
    rotation,
    *,
    telescope=MODEL,
    model_version=VERSION,
    zenith=str(ZENITH_DEG),
    azimuth=str(AZIMUTH_DEG),
    mirror_class=1,
    site_altitude_m,
):
    """showers.iact -> candidate.iact (camera frame, sim_telarray input).

    The atmosphere stage is obdeect propagation with the zero-optical-depth table (state applied,
    which obdeect stream to-simtel requires for camera-frame photons). The table ends at 999 nm
    (propagation accepts integer wavelengths below 1000 nm only), so photons above 1000 nm are
    dropped: 10315831 of 10888516 photons and 5.26 % of the weight in the validation run, which
    matches 5.3 % for a 1/lambda^2 spectrum over 100-2000 nm. They give no photoelectrons: the QE
    table is zero above about 760 nm. The p.e. bias moves by 0.17 % (-0.107 % +/- 0.216 % against
    +0.063 % +/- 0.187 % without the stage), within the errors. --no-extinction keeps the photons
    but leaves the factor pending, which to-simtel rejects.

    Returns (iact path, Bypass_Optics value of the converted telescope).
    """
    native, propagated, traced = (
        root / "showers.gst",
        root / "propagated.gst",
        root / "traced.gst",
    )
    model, iact = root / "telescope.model", root / "candidate.iact"
    common.command(
        cli.from_corsika(source), root / "from-corsika.log", stdout_file=native
    )
    common.command(
        cli.propagation_run(
            native,
            propagated,
            transmission=propagation_table(root),
            pathlen="0",
            site_altitude=f"{site_altitude_m:g}",
            seed=SEED,
            mode="weighted",
        ),
        root / "propagate.log",
    )
    common.command(
        cli.compile_model(
            model, telescope, model_version, seed=SEED, zenith_deg=zenith
        ),
        root / "compile.log",
    )
    common.command(
        cli.trace_stream(
            model,
            propagated,
            traced,
            seed=SEED,
            threads=2,
            telescopes=",".join(map(str, TELESCOPES)),
            pointing_zenith_deg=zenith,
            pointing_azimuth_deg=azimuth,
            telescope_transmission="full",
        ),
        root / "trace.log",
    )
    common.command(
        cli.obdeect(
            "stream",
            "to-simtel",
            camera_map=camera_map(root, rotation, mirror_class),
            o=iact,
            extra=[traced],
        ),
        root / "to-simtel.log",
    )
    return iact, bypass_from_log(root / "to-simtel.log")


def _add_arguments(parser):
    parser.add_argument("--input", type=Path, default=common.SHOWERS)
    parser.add_argument(
        "--config",
        type=Path,
        required=True,
        help="sim_telarray config generated by simtools for the array element (CTAO.cfg)",
    )
    parser.add_argument(
        "--telescope", default=MODEL, help="array element, e.g. LSTN-01"
    )
    parser.add_argument("--site", default=SITE, help="observatory of the configuration")
    parser.add_argument("--model-version", default=VERSION, help="production version")
    parser.add_argument(
        "--zenith",
        type=float,
        default=None,
        help="telescope zenith [deg]; default: shower header",
    )
    parser.add_argument(
        "--azimuth",
        type=float,
        default=None,
        help="telescope azimuth [deg]; default 180",
    )


def analyse(root, args):
    """Camera of the telescope against the obdeect candidate (sim_telarray with Bypass_Optics): (metrics, details)."""
    root = Path(root).resolve()
    source = args.input.resolve()
    config = args.config.resolve()
    config_dir = config.parent
    array_text = config.read_text()
    site = cfg_value(array_text, "site_config_name")
    if site != args.site:
        raise ValueError(f"configuration {config} is for site {site}, not {args.site}")
    altitude = float(cfg_value(array_text, "altitude"))
    cfg_text = (
        config_dir / f"CTAO-{args.telescope}.cfg"
    ).read_text()  # telescope parameters; CTAO.cfg is the array header
    zenith, azimuth, header = pointing(source, args.zenith, args.azimuth)
    unit = common.write_zero_depth_table(root, UNIT_ATMOSPHERE)
    extra = [
        "-I" + str(config_dir),
        "-DTELESCOPE=1",
        "-C",
        f"maximum_telescopes={len(TELESCOPES)}",
        "-C",
        f"atmospheric_transmission={unit}",
        # One telescope: the default array trigger needs two.
        "-C",
        "trigger_telescopes=1",
    ]
    keys = camera_keys(source)
    mirror_class = camera_class(cfg_text)
    factors = factor_record(cfg_text, config_dir, bypass=2 if mirror_class == 2 else 1)
    details = {
        "factors": factors,
        "config": str(config),
        "telescope": args.telescope,
        "site": site,
        "model_version": args.model_version,
        "input": str(source),
        "pointing": {
            "zenith_deg": float(zenith),
            "azimuth_deg": float(azimuth),
            "azimuth_convention": "N->E = header azimuth (CORSIKA PHIP) + 180 deg",
            "shower_header": header,
        },
        "physics_limits": {
            "photoelectron_relative_bias": f"max({cs.PE_BIAS_FLOOR}, {cs.SIGMA:g} se)",
            "trigger_probability": "paired |mean| > 5 se per telescope",
        },
    }
    camera_names = {0: camera_label(args.telescope, args.model_version)}
    reference = cs.simulate(
        root,
        source,
        "direct",
        bypass=0,
        config=str(config),
        extra=extra,
        zenith=zenith,
        azimuth=azimuth,
        altitude=f"{altitude:g}",
    )
    a = cs.camera_events(reference)
    metrics = {"candidate_pipeline_complete": 0}
    try:
        iact, bypass = candidate_stream(
            root,
            source,
            factors["camera_rotation_deg"],
            telescope=args.telescope,
            model_version=args.model_version,
            zenith=zenith,
            azimuth=azimuth,
            mirror_class=mirror_class,
            site_altitude_m=altitude,
        )
        metrics["candidate_pipeline_complete"] = 1
    except RuntimeError as error:
        details["candidate_blocked"] = str(error)
        from obdeect_validation.adapters import plotting

        plotting.message(
            root / "camera-comparison.png", "candidate pipeline blocked:\n" + str(error)
        )
        return metrics, details
    details["bypass_optics_candidate"] = bypass
    output = cs.simulate(
        root,
        iact,
        f"bypass{bypass}",
        bypass=bypass,
        config=str(config),
        extra=extra,
        zenith=zenith,
        azimuth=azimuth,
        altitude=f"{altitude:g}",
    )
    b = cs.camera_events(output)
    unmapped = (set(a) | set(b)) - set(keys)
    if unmapped:
        raise ValueError(
            f"camera event ids {sorted(unmapped)[:5]} not in the shower mapping"
        )
    metrics.update(
        {
            "reference_camera_events": len(a),
            "candidate_camera_events": len(b),
            "camera_event_id_delta": len(set(a) ^ set(b)),
        }
    )
    comparison = cs.compare_camera(a, b, root, camera_names)
    metrics.update(comparison)
    triggers = trigger_difference(a, b, keys)
    details["trigger_probability_per_telescope"] = triggers
    metrics["trigger_discordant_events"] = sum(
        row["candidate_only"] + row["reference_only"] for row in triggers.values()
    )
    metrics["trigger_mcnemar_p_min"] = min(
        row["mcnemar_p"] for row in triggers.values()
    )
    metrics["trigger_probability_limit_exceeded"] = int(
        any(row["flag"] for row in triggers.values())
    )
    metrics.update(centroid_offsets(a, b))
    return metrics, details


def main():
    common.results_main(analyse, "", add_arguments=_add_arguments)


if __name__ == "__main__":
    main()
