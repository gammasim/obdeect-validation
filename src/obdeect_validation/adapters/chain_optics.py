"""Optics isolation: CORSIKA -> obdeect trace-stream -> sim_telarray camera (Bypass_Optics=1), against direct sim_telarray.

Both sides use the same model: sim_telarray configuration generated by simtools from LSTN-01 7.0.0 (--config),
which is the model obdeect compiles. One telescope (LSTN-01 at the array origin, CORSIKA telescope 1).
Both runs use a unit atmosphere (optical depth 0). Factors and where they are applied are recorded in details.json.
"""
import argparse
import json
import re
import shutil
from pathlib import Path

import numpy as np
from eventio.iact import IACTFile

from obdeect_validation.adapters import chain_showers as cs

SHOWERS = '/validation/inputs/gamma-20deg-100-3000GeV.iact'
UNIT_ATMOSPHERE = '/validation/fixtures/unit-transmission.dat'
MODELS = '/models'
MODEL, VERSION = 'LSTN-01', '7.0.0'
SEED = 20261113
TELESCOPES = (1,)
ZENITH_DEG, AZIMUTH_DEG = 20, 180
PHYSICS_BIAS_LIMIT = 0.01  # mean p.e. per telescope-event within 1 % (plan step 5 target)


def cfg_value(text, key, default=None):
    match = re.search(rf'^\s*{key}\s*=\s*([^%\n]+)', text, re.M)
    return match.group(1).strip() if match else default


def camera_rotation_deg(config_dir, cfg_text):
    camera = cfg_value(cfg_text, 'camera_config_file')
    rotate = re.search(r'^\s*Rotate\s+([-\d.eE+]+)', (config_dir / camera).read_text(), re.M)
    return float(rotate.group(1))


def factor_record(cfg_text, config_dir):
    """Factors of the matched model and where each is applied (sim_telarray reference vs candidate)."""
    return {
        'mirror_reflectivity': {'file': cfg_value(cfg_text, 'mirror_reflectivity'),
                                'reference': 'sim_telarray ray tracing (Bypass_Optics=0)',
                                'candidate': 'obdeect compiled mirror response (trace-stream); sim_telarray not applied'},
        'mirror_degraded_reflection': {'value': cfg_value(cfg_text, 'mirror_degraded_reflection'),
                                       'reference': 'sim_telarray ray tracing (sim_absorb mirror_degraded)',
                                       'candidate': 'obdeect compiled mirror response (compiler.py); sim_telarray Bypass_Optics=1 only warns'},
        'telescope_transmission': {'value': cfg_value(cfg_text, 'telescope_transmission'),
                                   'reference': 'sim_telarray ray tracing (t0 kept)',
                                   'candidate': 'obdeect trace-stream --telescope-transmission full (t0 and t(theta)); sim_telarray forces t0=1 under bypass'},
        'camera_transmission': {'value': cfg_value(cfg_text, 'camera_transmission'),
                                'reference': 'sim_telarray', 'candidate': 'sim_telarray (Bypass_Optics=1, same value)'},
        'camera_degraded_efficiency': {'value': cfg_value(cfg_text, 'camera_degraded_efficiency'),
                                       'reference': 'sim_telarray', 'candidate': 'sim_telarray (same value)'},
        'quantum_efficiency': {'file': cfg_value(cfg_text, 'quantum_efficiency'),
                               'reference': 'sim_telarray', 'candidate': 'sim_telarray (Bypass_Optics=1 first cut and second cut)'},
        'atmosphere': {'reference': 'unit table (optical depth 0)', 'candidate': 'unit table (optical depth 0), no obdeect atmosphere stage'},
        'camera_rotation_deg': camera_rotation_deg(config_dir, cfg_text),
        'mirror_class': cfg_value(cfg_text, 'mirror_class'),
    }


def triggered(events, key, tel):
    return key in events and str(tel) in events[key].get('telescope_events', {})


def trigger_difference(reference, candidate, shower_ids):
    """Paired per-shower trigger difference per telescope; se from the paired differences."""
    rows = {}
    for tel in TELESCOPES:
        diff = np.asarray([float(triggered(candidate, key, tel)) - float(triggered(reference, key, tel))
                           for key in shower_ids])
        se = float(np.std(diff, ddof=1) / np.sqrt(len(diff))) if len(diff) > 1 else 0.0
        mean = float(diff.mean())
        rows[tel] = {'difference': mean, 'se': se, 'flag': int(abs(mean) > 5 * se)}
    return rows


def centroids(events):
    """Photo-electron-weighted centroid in pixel-index space per (event, telescope); not geometric."""
    result = {}
    for key, event in events.items():
        for tel, data in event.get('photoelectrons', {}).items():
            pe = np.asarray(data['photoelectrons'], dtype=float)
            if pe.sum() > 0:
                index = np.arange(len(pe))
                result[key, tel] = (float((pe * index).sum() / pe.sum()), float(pe.sum()))
    return result


def centroid_offsets(reference, candidate):
    """Mean and max |centroid difference| in pixel-index units over matched (event, telescope) pairs."""
    left, right = centroids(reference), centroids(candidate)
    keys = sorted(set(left) & set(right))
    offsets = [right[k][0] - left[k][0] for k in keys]
    return {'centroid_matched_samples': len(offsets),
            'centroid_mean_index_offset': float(np.mean(offsets)) if offsets else 0.0,
            'centroid_max_abs_index_offset': float(np.max(np.abs(offsets))) if offsets else 0.0}


def write_stub_plot(path, text):
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    fig, axis = plt.subplots(figsize=(8, 3))
    axis.axis('off')
    axis.text(0.02, 0.5, text, va='center', wrap=True)
    fig.savefig(path, dpi=120)
    plt.close(fig)


def camera_map(root, rotation):
    camera = root / 'camera-map.txt'
    camera.write_text('# telescope_id mirror_class camera_rotation_deg\n'
                      + ''.join(f'{tel} 1 {rotation}\n' for tel in TELESCOPES))
    return camera


def candidate_stream(root, source, rotation):
    """showers.iact -> candidate.iact (camera frame, sim_telarray Bypass_Optics=1 input). No atmosphere."""
    native, traced = root / 'showers.gst', root / 'traced.gst'
    model, iact = root / 'lst.model', root / 'candidate.iact'
    cs.command(['obdeect', 'stream', 'from-corsika', source], root / 'from-corsika.log', stdout_file=native)
    cs.command(['obdeect', 'ray-tracing', 'compile', '--simulation-models', MODELS, '--model', MODEL,
                '--version', VERSION, '--seed', SEED, '--output', model], root / 'compile.log')
    cs.command(['obdeect', 'ray-tracing', 'trace-stream', '--model', model, '--seed', SEED, '--threads', 2,
                '--telescopes', ','.join(map(str, TELESCOPES)),
                '--pointing-zenith-deg', ZENITH_DEG, '--pointing-azimuth-deg', AZIMUTH_DEG,
                '--telescope-transmission', 'full', '-i', native, '-o', traced], root / 'trace.log')
    cs.command(['obdeect', 'stream', 'to-simtel', '--camera-map', camera_map(root, rotation), '-o', iact, traced],
               root / 'to-simtel.log')
    return iact


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--input', type=Path, default=Path(SHOWERS))
    parser.add_argument('--config', type=Path, required=True,
                        help='sim_telarray config generated by simtools for LSTN-01 7.0.0 (CTAO.cfg)')
    args = parser.parse_args()
    root = Path.cwd().resolve()
    source = args.input.resolve()
    config = args.config.resolve()
    config_dir = config.parent
    cfg_text = (config_dir / 'CTAO-LSTN-01.cfg').read_text()  # telescope parameters; CTAO.cfg is the array header
    unit = root / 'unit-atmosphere.dat'
    shutil.copyfile(UNIT_ATMOSPHERE, unit)
    extra = ['-I' + str(config_dir), '-DTELESCOPE=1', '-C', f'maximum_telescopes={len(TELESCOPES)}',
             '-C', f'atmospheric_transmission={unit}',
             # One telescope: the default array trigger needs two.
             '-C', 'trigger_telescopes=1']
    shower_ids = [str(event.event_number) for event in IACTFile(source)]
    factors = factor_record(cfg_text, config_dir)
    details = {'factors': factors, 'config': str(config),
               'physics_limits': {'photoelectron_relative_bias': PHYSICS_BIAS_LIMIT,
                                  'trigger_probability': 'paired |mean| > 5 se per telescope'}}
    reference = cs.simulate(root, source, 'direct', bypass=0, config=str(config), extra=extra)
    a = cs.camera_events(reference)
    metrics = {'candidate_pipeline_complete': 0}
    try:
        iact = candidate_stream(root, source, factors['camera_rotation_deg'])
        metrics['candidate_pipeline_complete'] = 1
    except RuntimeError as error:
        details['candidate_blocked'] = str(error)
        write_stub_plot(root / 'camera-comparison.png', 'candidate pipeline blocked:\n' + str(error))
        (root / 'metrics.json').write_text(json.dumps(metrics, indent=2) + '\n')
        (root / 'details.json').write_text(json.dumps(details, indent=2) + '\n')
        return
    output = cs.simulate(root, iact, 'bypass1', bypass=1, config=str(config), extra=extra)
    b = cs.camera_events(output)
    metrics.update({'reference_camera_events': len(a), 'candidate_camera_events': len(b),
                    'camera_event_id_delta': len(set(a) ^ set(b))})
    comparison = cs.compare_camera(a, b, root)
    metrics.update(comparison)
    metrics['photoelectron_bias_limit_exceeded'] = int(abs(comparison['photoelectron_relative_bias'])
        > max(PHYSICS_BIAS_LIMIT, 5 * comparison['photoelectron_relative_bias_se']))  # same limit as compare_camera
    triggers = trigger_difference(a, b, shower_ids)
    details['trigger_probability_per_telescope'] = triggers
    metrics['trigger_probability_limit_exceeded'] = int(any(row['flag'] for row in triggers.values()))
    metrics.update(centroid_offsets(a, b))
    (root / 'metrics.json').write_text(json.dumps(metrics, indent=2) + '\n')
    (root / 'details.json').write_text(json.dumps(details, indent=2) + '\n')


if __name__ == '__main__':
    main()
